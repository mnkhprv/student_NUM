# ── 3. Thresholds and majority arithmetic ───────────────────────────────
def check_thresholds() -> list[Finding]:
    out = []
    quorum = TOTAL_SEATS // 2 + 1
    from .articles import get
    law = get("27.6").threshold.seats_needed(TOTAL_SEATS)
    override = get("33.1.1").threshold.seats_needed(TOTAL_SEATS, present=quorum)
    if override < law:
        out.append(Finding(
            "THRESHOLD_INVERSION", "high", "bug", ("33.1.1", "27.6"),
            f"Хоригийг {override} санал даван туулж болох ч хууль батлахад {law} санал хэрэгтэй",
            f"Хоригийн босго «оролцсон» гишүүний 2/3. Ирц {quorum} бол {override} санал хангалттай — "
            f"хуулийг анх батлах босгоос ({law}, нийт гишүүний олонхи) бага. Хориг нь хууль батлахаас хялбар саад.",
            evidence=q("33.1.1", "чуулганд оролцсон нийт гишүүний гуравны хоёр нь хүлээж аваагүй бол"),
            fix="33.1.1 (өөрчлөлт): «...Улсын Их Хурлын нийт гишүүний гуравны хоёр нь хүлээж аваагүй бол...»"))
    for a, p in all_provisions():
        if p.pid == "35.2":  # covered by UNDEFINED_SUPERMAJORITY with the quote
            continue
        if p.threshold and (p.threshold.fraction is None and p.threshold.base is not Base.VOTERS or p.threshold.base is Base.UNDEFINED):
            out.append(Finding("UNDEFINED_THRESHOLD", "high", "text", (p.pid,),
                               f"{p.pid}: санал хураалтын босго тоогоор тодорхойлогдоогүй ({p.threshold.wording})",
                               p.summary, evidence="[TEXT]"))
    return out


def majority_capture_table(seats=TOTAL_SEATS) -> list[dict]:
    """What a single party can do alone at a given seat count."""
    from .articles import get
    powers = [("Хууль батлах", "27.6"), ("Ерөнхий сайдыг огцруулах", "43.1"), ("УИХ өөрөө тарах", "22.2"),
              ("Санал асуулга (Үндсэн хууль)", "68.2"), ("Үндсэн хууль өөрчлөх", "69.1")]
    rows = []
    for name, pid in powers:
        need = get(pid).threshold.seats_needed(seats)
        rows.append({"power": name, "pid": pid, "seats_needed": need, "share": round(need / seats, 3)})
    return rows


