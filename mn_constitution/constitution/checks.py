"""Rule-based checker. Every TEXT finding quotes the official Mongolian wording via
`q(pid, phrase)`, which raises if the phrase is not literally in that provision —
so no finding can rest on a paraphrase or on the English translation."""
from __future__ import annotations

from collections import Counter

from .articles import ARTICLES, TOTAL_SEATS, all_provisions
from .model import Base, Finding, Kind
from .procedures import MACHINES, stall_points, undefined_transitions
from .text_mn import linguistic_profile, lookup, parse

ARTS = parse()


def q(pid: str, phrase: str) -> str:
    text = lookup(ARTS, pid)
    if phrase not in text:
        raise AssertionError(f"quote not found in {pid}: {phrase!r}")
    return f"[TEXT: {pid}] «{phrase}»"


# ── 0. Coverage: model ↔ Mongolian text ─────────────────────────────────
def check_coverage() -> list[Finding]:
    out = []
    model_articles = {a.number for a in ARTICLES}
    text_articles = set(ARTS)
    for missing in sorted(text_articles - model_articles, key=lambda x: (len(x), x)):
        out.append(Finding("COVERAGE", "low", "text", (missing,), "Загварт ороогүй зүйл", f"{missing} дугаар зүйл загварт алга"))
    for _, p in all_provisions():
        if not lookup(ARTS, p.pid.replace(".b", "").replace(".c", "")):
            out.append(Finding("COVERAGE", "low", "text", (p.pid,), "Текстэд олдоогүй заалт", p.pid))
    return out


# ── 1. Procedures ────────────────────────────────────────────────────────
def check_procedures() -> list[Finding]:
    out = []
    for m in MACHINES:
        for state, event in undefined_transitions(m):
            case = m.case.get((state, event), "")
            sev = "critical" if case else "high"
            out.append(Finding(
                "UNDEFINED_TRANSITION", sev, "bug", (m.title,),
                f"{m.title}: «{state}» төлөвт «{event}» болбол юу болох нь заагаагүй",
                m.note.get((state, event), ""),
                evidence=f"[CASE: {case}]" if case else "[INFERENCE: state-machine model]"))
        for (state, event), t in stall_points(m):
            out.append(Finding(
                "STALL_POINT", "high", "bug", (t.pid,),
                f"{t.pid}: {t.actor or 'тоглогч'} үйлдэл хийх үүрэгтэй ч хугацаа, анхдагч үр дагавар алга",
                f"{m.title} — «{state}» → «{event}». Үйлдэл хийхгүй байх нь процессыг хязгааргүй зогсооно.",
                evidence="[INFERENCE: state-machine model]"))
    return out


