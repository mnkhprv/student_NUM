SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3}


def run_all() -> list[Finding]:
    fs = (check_coverage() + check_procedures() + check_delegations() + check_thresholds()
          + check_capture() + check_terms() + check_modality() + check_text_defects() + check_version())
    from . import statutes
    if statutes.available():                      # statute layer: annotate gaps that ordinary law fills
        fs = statutes.apply(fs) + statutes.statute_findings()
    seen, out = set(), []
    for f in fs:
        if f.key() not in seen:
            seen.add(f.key())
            out.append(f)
    return sorted(out, key=lambda f: (SEV_ORDER[f.severity], f.rule))
