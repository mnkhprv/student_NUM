"""Statute layer: where an ordinary law fills a gap the Constitution leaves open.

A Closure never deletes a constitutional finding — the gap stays at constitutional level,
because the statute can be changed by a simple majority (often of the body it constrains).
It records the statute text (verbatim via q_law) and lowers the severity:
  closed  -> "low"            (statute sets the deadline AND the consequence)
  partial -> one level lower  (statute narrows the gap but leaves a hole)
  context -> unchanged        (statute is relevant but does not settle the question)
"""
from __future__ import annotations

from dataclasses import dataclass

from .laws import load, q_law, q_law_note
