def available() -> bool:
    """Statute texts present (they come from scripts/ingest_archive.py, not from the repo)."""
    return all(load(l) for c in CLOSURES for l, _, _ in c.cites)


def apply(findings: list[Finding]) -> list[Finding]:
    """Annotate findings closed or narrowed by statute (in place) and return them."""
    for f in findings:
        for c in CLOSURES:
            if c.applies(f):
                tag = {"closed": "ХУУЛИАР ХААГДСАН", "partial": "ХУУЛИАР ХЭСЭГЧЛЭН ХААГДСАН",
                       "context": "ХУУЛЬД ХОЛБОГДОХ ЗААЛТ БИЙ"}[c.status]
                f.severity = {"closed": "low", "partial": STEP_DOWN[f.severity], "context": f.severity}[c.status]
                f.title = f"[{tag}] {f.title}"
                f.detail = (f.detail + " " if f.detail else "") + f"Хуулийн түвшинд: {c.gap}"
                f.evidence = (f.evidence + " " if f.evidence else "") + c.evidence()
                break
    return findings
