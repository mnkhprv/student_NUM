STEP_DOWN = {"critical": "high", "high": "medium", "medium": "low", "low": "low"}


@dataclass(frozen=True)
class Closure:
    rule: str                        # finding rule it applies to
    match: tuple[str, ...]           # all substrings must occur in the finding title
    status: str                      # "closed" | "partial" | "context"
    cites: tuple[tuple[str, str, str], ...]   # (law_id, pid, verbatim phrase)
    gap: str                         # what the statute still leaves open (Mongolian)

    def evidence(self) -> str:
        return " ".join(q_law(l, p, ph) for l, p, ph in self.cites)

    def applies(self, f: Finding) -> bool:
        return f.rule == self.rule and all(m in f.title for m in self.match)


